// ── רשתות זמינות לפי מוצר (דטרמיניסטי לפי id) ──
const _CK = ['shufersal','ramilevi','mega','victory','yeinot','yohananof','osher','yesh']
function _assignChains(id) {
  const count = 3 + (id % 4)   // 3–6 רשתות
  return _CK
    .map((c, i) => [c, (id * 31 + i * 11) % 100])
    .sort((a, b) => a[1] - b[1])
    .map(x => x[0])
    .slice(0, count)
}

